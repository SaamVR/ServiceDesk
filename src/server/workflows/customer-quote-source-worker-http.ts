import { createHash, randomUUID, timingSafeEqual } from "node:crypto";
import { createClient, type SupabaseClient } from "@supabase/supabase-js";
import { supabasePublicConfig } from "@/features/auth/supabase-public-config";
import { operationalDatabaseMode } from "@/features/auth/operational-preview-mode";
import type { SupabaseRpcClient } from "@/server/core/payment-application-postgres";
import {
  runInternalQuoteSourceRecoveryBatch,
  type InternalSourceRecoverySummary,
} from "./customer-quote-source-recovery";

type RuntimeSettings = {
  workerEnabled: boolean;
  automationEnabled: boolean;
  secret?: string;
  databaseMode: string;
  supabaseUrl?: string;
  serviceRoleKey?: string;
};
export interface QuoteSourceWorkerHttpDependencies {
  settings?: () => RuntimeSettings;
  createService?: (url: string, key: string) => SupabaseClient;
  runBatch?: typeof runInternalQuoteSourceRecoveryBatch;
  workerId?: () => string;
}

function realSettings(): RuntimeSettings {
  const publicConfig = supabasePublicConfig();
  return {
    workerEnabled: process.env.SERVICEDESK_QUOTE_SOURCE_WORKER_ENABLED === "true",
    automationEnabled: process.env.SERVICEDESK_AUTO_INTERNAL_QUOTE_ACCEPTED === "true",
    secret: process.env.SERVICEDESK_QUOTE_SOURCE_WORKER_SECRET,
    databaseMode: operationalDatabaseMode(),
    supabaseUrl: publicConfig?.url,
    serviceRoleKey: process.env.SUPABASE_SERVICE_ROLE_KEY,
  };
}

function authenticate(auth: string | null, secret: string): boolean {
  // A one-off server-only token, never a customer bearer/access token.
  // Hash equal-length digests so token comparison is constant time.
  if (secret.length < 40 || secret.length > 512) return false;
  const received = /^Bearer (\S{40,512})$/.exec(auth ?? "")?.[1];
  if (!received) return false;
  const digest = (value: string) => createHash("sha256").update(value).digest();
  return timingSafeEqual(digest(received), digest(secret));
}

const json = (payload: Record<string, unknown>, status: number) =>
  Response.json(payload, {
    status,
    headers: { "Cache-Control": "private, no-store", "X-Content-Type-Options": "nosniff" },
  });

/**
 * Privileged server-to-server POST only. The route never accepts a tenant,
 * action, quote ID, provider target, or limit from the HTTP caller.
 *
 * The entire recovery stack is opt-in and fail-closed. This is not yet
 * scheduled anywhere and SQL 0062 must be approved/applied separately.
 */
export async function handleInternalQuoteSourceWorkerPost(
  request: Request,
  deps: QuoteSourceWorkerHttpDependencies = {},
): Promise<Response> {
  if (request.method !== "POST") return json({ ok: false, code: "METHOD_NOT_ALLOWED" }, 405);
  const settings = (deps.settings ?? realSettings)();
  if (!settings.workerEnabled || !settings.automationEnabled || !settings.secret ||
      settings.databaseMode !== "SERVICE_ROLE") {
    return json({ ok: false, code: "NOT_CONFIGURED" }, 404);
  }
  if (!authenticate(request.headers.get("authorization"), settings.secret)) {
    return json({ ok: false, code: "UNAUTHORIZED" }, 401);
  }
  if (!settings.supabaseUrl || !settings.serviceRoleKey ||
      settings.serviceRoleKey.length < 40) {
    return json({ ok: false, code: "BACKEND_UNAVAILABLE" }, 503);
  }
  try {
    const createService = deps.createService ?? ((url, key) => createClient(url, key, {
      auth: { persistSession: false, autoRefreshToken: false },
    }));
    const service = createService(settings.supabaseUrl, settings.serviceRoleKey);
    // A distinct lease identity is generated by this trusted server for every
    // invocation. No caller-selected worker ID or branch scope is accepted.
    const workerId = (deps.workerId ?? (() => "quote_" + randomUUID()))();
    const result: InternalSourceRecoverySummary =
      await (deps.runBatch ?? runInternalQuoteSourceRecoveryBatch)({
        service, rpc: service as unknown as SupabaseRpcClient, workerId, maxBatch: 10,
      }, { enabled: () => true });
    if (result.state === "CLAIM_UNVERIFIED") {
      return json({ ok: false, code: "RECOVERY_UNVERIFIED" }, 503);
    }
    return json({
      ok: true, state: result.state, claimed: result.claimed,
      completed: result.completed, retried: result.retryPending,
      deadLetter: result.deadLetter, skipped: result.skipped,
      completionNotVerified: result.completionNotVerified,
      providerMessagesSent: 0,
    }, result.completionNotVerified ? 503 : 200);
  } catch {
    // Do not disclose database, secret, event, tenant or exception details.
    return json({ ok: false, code: "RECOVERY_UNAVAILABLE" }, 503);
  }
}
