import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { describe, expect, it } from "vitest";
import { RecurrenceRulePreview } from "../../src/features/recurrence/RecurrenceRulePreview";

const rule = {
  id: "rule-1", workspaceId: "tenant-1", requestId: "request-1",
  propertyId: "property-1", frequency: "WEEKLY" as const, timezone: "UTC",
  localStartTime: "09:30", startsOn: "2026-10-17", status: "ACTIVE" as const,
  generatedOccurrences: 0, nextOccurrenceOn: "2026-10-24",
  version: 1, createdAt: "2026-10-17T00:00:00Z",
  updatedAt: "2026-10-17T00:00:00Z",
};

describe("R17F recurrence preview command truth", () => {
  it("never renders an enabled inert action even when parent claims actionsInjected", () => {
    const markup = renderToStaticMarkup(createElement(RecurrenceRulePreview, {
      rule, audience: "staff", actionsInjected: true,
    }));
    const buttons = markup.match(/<button\b[^>]*>/g) ?? [];
    expect(buttons).toHaveLength(2);
    for (const button of buttons) {
      expect(button).toContain("disabled");
      expect(button).toContain('aria-disabled="true"');
    }
    expect(markup).toContain("Preview only: these recurrence controls cannot submit");
    expect(markup).toContain("0 generated by server");
    expect(markup).toContain("2026-10-24");
  });

  it("never exposes paused/customer controls without an actual RPC command binding", () => {
    for (const status of ["PAUSED", "COMPLETED"] as const) {
      const html = renderToStaticMarkup(createElement(RecurrenceRulePreview, {
        rule: { ...rule, status }, audience: "staff", actionsInjected: true,
      }));
      const buttons = html.match(/<button\b[^>]*>/g) ?? [];
      expect(buttons.length, status).toBeGreaterThan(0);
      expect(buttons.every(x => x.includes("disabled") && x.includes('aria-disabled="true"'))).toBe(true);
    }
    const customer = renderToStaticMarkup(createElement(RecurrenceRulePreview, {
      rule, audience: "customer", actionsInjected: true,
    }));
    expect((customer.match(/<button\b[^>]*>/g) ?? []).every(b => b.includes("disabled"))).toBe(true);
  });

  it("does not invent materialized visits when only a next recurrence date exists", () => {
    const html = renderToStaticMarkup(createElement(RecurrenceRulePreview, {
      rule, audience: "staff", actionsInjected: true, materializedVisits: [],
    }));
    expect(html).toContain("No VisitDTO materialized");
    expect(html).toContain("Future visits are not synthesized in Product");
    expect(html).not.toContain("Crew unassigned");
  });
});
